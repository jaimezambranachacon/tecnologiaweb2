// 2. FUNCIONES DE INTERACTIVIDAD (Usando GSAP para animaciones fluidas)
window.abrirModalDuo = function(mesIndex, estIndex) {
    const dataMes = window.duoData[mesIndex];
    const estudiante = dataMes.estudiantes[estIndex];
    const fotoUrl = estudiante.foto || `https://ui-avatars.com/api/?name=${encodeURIComponent(estudiante.nombre)}&background=random&color=fff`;

    // Cargar datos en el DOM
    document.getElementById('mdl_nombre').innerText = estudiante.nombre;
    document.getElementById('mdl_foto').src = fotoUrl;
    document.getElementById('mdl_posicion').innerText = estudiante.posicion + '° Lugar';
    document.getElementById('mdl_mes').innerText = 'Podio de ' + dataMes.mes;
    document.getElementById('mdl_xp').innerHTML = '<i class="fas fa-bolt text-yellow-400"></i> ' + estudiante.xp;

    const modalOverlay = document.getElementById('modal_overlay');
    const modalBox = document.getElementById('modal_box');

    // Mostrar el modal
    modalOverlay.classList.remove('hidden');
    modalOverlay.classList.add('flex');

    // Animaciones con GSAP
    gsap.fromTo(modalOverlay, 
        { opacity: 0 }, 
        { opacity: 1, duration: 0.3, ease: "power2.out" }
    );
    gsap.fromTo(modalBox, 
        { scale: 0.8, y: 30, opacity: 0 }, 
        { scale: 1, y: 0, opacity: 1, duration: 0.5, ease: "back.out(1.5)" }
    );
};

window.cerrarModalDuo = function() {
    const modalOverlay = document.getElementById('modal_overlay');
    const modalBox = document.getElementById('modal_box');

    // Animación de salida con GSAP
    gsap.to(modalBox, { scale: 0.9, y: 20, opacity: 0, duration: 0.3, ease: "power2.in" });
    gsap.to(modalOverlay, { opacity: 0, duration: 0.3, ease: "power2.in", onComplete: () => {
        modalOverlay.classList.add('hidden');
        modalOverlay.classList.remove('flex');
    }});
};

